function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf8");
}

function run(args, cwd) {
  return spawnSync(process.execPath, [cli, ...args], {
    cwd,
    encoding: "utf8",
  });
}

function runTool(command, args, cwd) {
  const env = { ...process.env };
  for (const key of gitLocalEnvKeys) delete env[key];
  const result = spawnSync(command, args, { cwd, encoding: "utf8", env });
  assert.equal(result.status, 0, `${command} ${args.join(" ")} failed\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`);
  return result;
}

function assertOk(result, label) {
  assert.equal(result.status, 0, `${label}\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function assertContainsPath(text, path) {
  assert.match(text, new RegExp(escapeRegExp(path)));
}

function assertGeneratedFrontmatter(text, filename, fields = []) {
  const expected = [
    "---",
    `generated-by: "nosedive"`,
    `generated-file: "${filename}"`,
    "do-not-edit: true",
    `gist: "Generated by nosedive from kb; do not edit by hand."`,
    ...fields,
    "---",
    "",
  ].join("\n");
  assert.equal(text.startsWith(expected), true, `expected generated frontmatter:\n${expected}\nactual start:\n${text.slice(0, 300)}`);
}


import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readmePath = join(root, "README.md");
const kbDir = join(root, "kb");
const beginMarker = "<!-- BEGIN nosedive-faq -->";
const endMarker = "<!-- END nosedive-faq -->";
const checkOnly = process.argv.includes("--check");

function fail(message) {
	throw new Error(message);
}

function read(path) {
	return readFileSync(path, "utf8");
}

function rel(path) {
	return relative(root, path).replaceAll("\\", "/");
}

function parseFrontmatter(text, label) {
	const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
	if (!match) return undefined;
	try {
		return { raw: YAML.parse(match[1] ?? "") ?? {}, body: text.slice(match[0].length) };
	} catch (err) {
		const detail = err instanceof Error ? err.message : String(err);
		fail(`${label} has invalid YAML frontmatter: ${detail}`);
	}
}

function h1(body, label) {
	const match = /^# ([^\r\n]+)\s*$/m.exec(body);
	if (!match) fail(`${label} FAQ document is missing an H1`);
	return match[1];
}

function faqDocs() {
	const docs = [];
	for (const filename of readdirSync(kbDir)
		.filter((name) => name.endsWith(".md"))
		.sort()) {
		const path = join(kbDir, filename);
		const parsed = parseFrontmatter(read(path), filename);
		if (!parsed || parsed.raw.kind !== "faq") continue;
		const gist = String(parsed.raw.gist ?? "").trim();
		if (!gist) fail(`${filename} FAQ document is missing a gist`);
		docs.push({ filename, gist, heading: h1(parsed.body, filename), relPath: rel(path) });
	}
	return docs.sort((a, b) => a.heading.localeCompare(b.heading));
}

function renderFaq() {
	return [
		beginMarker,
		"<!-- Generated by `npm run faq:surface`; do not edit by hand. -->",
		"",
		"## FAQ",
		"",
		...faqDocs().map((doc) => `- [${doc.heading}](${doc.relPath}) — ${doc.gist}`),
		endMarker,
	].join("\n");
}

function replaceGeneratedFaq(readme, generated) {
	const existingRegion = new RegExp(`${beginMarker}[\\s\\S]*?${endMarker}`);
	if (existingRegion.test(readme)) return readme.replace(existingRegion, generated);
	fail(`README.md is missing ${beginMarker} / ${endMarker} markers`);
}

const readme = read(readmePath);
const updated = replaceGeneratedFaq(readme, renderFaq());

if (checkOnly) {
	if (updated !== readme) {
		console.error("README FAQ is stale. Run `npm run faq:surface`.");
		process.exit(1);
	}
	console.log("README FAQ is up to date.");
} else {
	writeFileSync(readmePath, updated, "utf8");
	console.log("Updated README FAQ.");
}
